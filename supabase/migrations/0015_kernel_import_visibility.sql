-- 0015_kernel_import_visibility
-- Forward-only migration (rule 34). Covered by packages/modules/core/src/__tests__/import.integration.test.ts
-- ("an import and its files are visible only to the user who started it and to company admins").
-- An import record carries the user's source file and errores.csv as attachments: beyond company RLS, a member
-- sees and touches only the imports they started; the company admin sees every import of the company. The
-- attachment processes require the record to be visible through kernel.v_imports, so the files follow.

create policy own_or_admin on kernel.imports as restrictive for all to authenticated
  using (started_by = (select kernel.current_user_id()) or (select kernel.is_company_admin()))
  with check (started_by = (select kernel.current_user_id()) or (select kernel.is_company_admin()));

-- The masked view (generated by maskedViewSql up to its `from`) with the same predicate, so the view never depends
-- on the base table's policies alone.
create or replace view kernel.v_imports with (security_invoker = true) as
select
  "id",
  "company_id",
  case when (select kernel.field_visible('kernel.import', 'entity')) then "entity" else null end as "entity",
  case when (select kernel.field_visible('kernel.import', 'status')) then "status" else null end as "status",
  case when (select kernel.field_visible('kernel.import', 'rows_total')) then "rows_total" else null end as "rows_total",
  case when (select kernel.field_visible('kernel.import', 'rows_ok')) then "rows_ok" else null end as "rows_ok",
  case when (select kernel.field_visible('kernel.import', 'rows_failed')) then "rows_failed" else null end as "rows_failed",
  case when (select kernel.field_visible('kernel.import', 'file_attachment_id')) then "file_attachment_id" else null end as "file_attachment_id",
  case when (select kernel.field_visible('kernel.import', 'errors_attachment_id')) then "errors_attachment_id" else null end as "errors_attachment_id",
  case when (select kernel.field_visible('kernel.import', 'started_by')) then "started_by" else null end as "started_by",
  case when (select kernel.field_visible('kernel.import', 'finished_at')) then "finished_at" else null end as "finished_at",
  case when (select kernel.field_visible('kernel.import', 'error')) then "error" else null end as "error",
  "created_at",
  "updated_at"
from kernel.imports
where started_by = (select kernel.current_user_id()) or (select kernel.is_company_admin());
grant select on kernel.v_imports to authenticated;
