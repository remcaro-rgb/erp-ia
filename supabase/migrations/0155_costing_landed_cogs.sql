-- A landed cost that arrives after some of the receipt's units were sold sends the share of those units to cost of sales in the current
-- period (nothing in a past period is rewritten). The share of the units still on hand raises the layer as before (event kind landed_cost);
-- the share of the units already gone is recorded as a cost event of the new kind landed_cost_cogs (qty 0, layer unchanged: the audit record
-- of the adjustment) and posts Dr cogs in the allocation's entry.

-- The new event kind and cost source; a landed cost's events (both kinds) carry no quantity and may be of either sign (a void is negative).
alter table costing.cost_events drop constraint if exists cost_events_kind_check;
alter table costing.cost_events add constraint cost_events_kind_check
  check (kind in ('receipt', 'issue', 'sale_issue', 'sale_return', 'adjustment', 'transfer_out', 'transfer_in', 'landed_cost', 'landed_cost_cogs', 'reversal'));
alter table costing.cost_events drop constraint if exists cost_events_cost_source_check;
alter table costing.cost_events add constraint cost_events_cost_source_check
  check (cost_source in ('line', 'average', 'standard', 'original_issue', 'transfer', 'none', 'landed_cost', 'reversal', 'last_known', 'landed_cost_cogs'));
alter table costing.cost_events drop constraint if exists cost_events_qty_check;
alter table costing.cost_events add constraint cost_events_qty_check check ((kind in ('landed_cost', 'landed_cost_cogs')) = (qty = 0));
alter table costing.cost_events drop constraint if exists cost_events_amount_sign_check;
alter table costing.cost_events add constraint cost_events_amount_sign_check check (kind in ('landed_cost', 'landed_cost_cogs') or amount = 0 or sign(amount) = sign(qty));

-- The split of each line's share (R45-7): every allocation made before this file sent its whole share to stock.
alter table costing.landed_cost_lines add column if not exists amount_stock numeric(18,4), add column if not exists amount_cogs numeric(18,4) not null default 0;
update costing.landed_cost_lines set amount_stock = amount where amount_stock is null;
alter table costing.landed_cost_lines alter column amount_stock set not null;
alter table costing.landed_cost_lines drop constraint if exists landed_cost_lines_split_check;
alter table costing.landed_cost_lines add constraint landed_cost_lines_split_check
  check (amount_stock >= 0 and amount_cogs >= 0 and amount_stock + amount_cogs = amount);

-- The cost center of the cost of sales part (an accounting dimension, as a sales delivery carries it; the ledger checks it).
alter table costing.landed_costs add column if not exists cost_center_id uuid;

