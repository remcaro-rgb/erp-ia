-- The shipped allocation rules (packages/modules/costing/src/rules.ts) gain the cost of sales debit per line (R45-3); a zero line is dropped
-- by the engine, so an allocation with nothing sold posts as before. accounting.posting_rule.sync only adds missing rules, so the copies a
-- company already holds are rewritten here: those nobody touched (is_default, not is_modified) and still without a cogs line. A copy the admin
-- edited is left alone (an allocation with sold units then posts unbalanced and is refused until the admin adds the line).
update accounting.posting_rules
   set template = jsonb_insert(template, '{lines,1}',
         '{"role": "cogs", "side": "debit", "forEach": "$.lines[*]", "amount": "$.cogsAdjustment", "costCenter": "$.costCenterId"}'::jsonb)
 where event = 'costing.landed_cost.allocated' and is_default and not is_modified
   and not exists (select 1 from jsonb_array_elements(template->'lines') l where l->>'role' = 'cogs');

do $$
declare
  kept text;
begin
  select string_agg(distinct company_id::text, ', ') into kept
    from accounting.posting_rules
   where event = 'costing.landed_cost.allocated' and is_modified
     and not exists (select 1 from jsonb_array_elements(template->'lines') l where l->>'role' = 'cogs');
  if kept is not null then
    raise notice 'landed cost rules without a cogs line left as the admin edited them, for companies: %', kept;
  end if;
end $$;

-- An allocation whose event is still parked (accounting off, not yet delivered to accounting) was written before this file: its lines carry
-- no cogsAdjustment, which the rewritten rule reads. Every such allocation sent its whole share to stock, so each line gets cogsAdjustment 0.
update kernel.outbox o
   set payload = jsonb_set(o.payload, '{lines}', (
         select coalesce(jsonb_agg(l || '{"cogsAdjustment": 0}'::jsonb order by n), '[]'::jsonb)
           from jsonb_array_elements(o.payload->'lines') with ordinality as x(l, n)))
 where o.event = 'costing.landed_cost.allocated'
   and exists (select 1 from jsonb_array_elements(o.payload->'lines') l where not (l ? 'cogsAdjustment'))
   and not exists (select 1 from kernel.outbox_deliveries d where d.outbox_id = o.id and d.module_id = 'accounting');
