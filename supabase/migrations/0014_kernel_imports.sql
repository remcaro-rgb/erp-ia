-- 0014_kernel_imports
-- Forward-only migration (rule 34). Covered by packages/modules/core/src/__tests__/import.integration.test.ts
-- (an import needs an entity with a create process; core's parties are the target).
-- Mass import from Excel / CSV on any entity (design §5.11, §9, rule 20). One row per imported file: the target
-- entity, the run's status and counts, the source file and `errores.csv` as attachments of the import record.
-- Members of the company read their company's imports; the row is created only through `kernel.import.run`, and
-- its status and counts are kept by the import workflow (service role).

create table kernel.imports (
  id                   uuid primary key default kernel.uuid_v7(),
  company_id           uuid not null references kernel.companies (id),
  entity               text not null check (entity ~ '^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)+$'),
  file_attachment_id   uuid references kernel.attachments (id),
  status               text not null default 'queued' check (status in ('queued', 'running', 'done', 'failed')),
  rows_total           int not null default 0 check (rows_total >= 0),
  rows_ok              int not null default 0 check (rows_ok >= 0),
  rows_failed          int not null default 0 check (rows_failed >= 0),
  errors_attachment_id uuid references kernel.attachments (id),
  started_by           uuid not null references kernel.users (id),
  finished_at          timestamptz,
  -- Why a run failed as a whole (the file could not be read); row errors go to errores.csv.
  error                text,
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now(),
  created_by           uuid default kernel.current_user_id(),
  updated_by           uuid
);
create index imports_company_created_idx on kernel.imports (company_id, created_at desc);
create index imports_started_by_idx on kernel.imports (started_by);
create index imports_file_attachment_id_idx on kernel.imports (file_attachment_id);
create index imports_errors_attachment_id_idx on kernel.imports (errors_attachment_id);

create trigger imports_touch_updated before update on kernel.imports
  for each row execute function kernel.touch_updated();

-- Members insert through kernel.import.run; status and counts change only with the service role (the workflow).
grant select, insert on kernel.imports to authenticated;
grant all on kernel.imports to service_role;
select kernel.enable_company_rls('kernel', 'imports');
select kernel.enable_row_audit('kernel', 'imports');

-- Writes only through the process pipeline (rule 1): the caller starts an import as themselves.
create policy via_process_insert on kernel.imports as restrictive for insert to authenticated
  with check (
    coalesce(current_setting('erp.audit_process_id', true), '') = 'kernel.import.run'
    and started_by = (select kernel.current_user_id())
  );

-- The masked read view of kernel.import, generated by maskedViewSql (rule 14).
create or replace view kernel.v_imports with (security_invoker = true) as
select
  "id",
  "company_id",
  case when (select kernel.field_visible('kernel.import', 'entity')) then "entity" else null end as "entity",
  case when (select kernel.field_visible('kernel.import', 'status')) then "status" else null end as "status",
  case when (select kernel.field_visible('kernel.import', 'rows_total')) then "rows_total" else null end as "rows_total",
  case when (select kernel.field_visible('kernel.import', 'rows_ok')) then "rows_ok" else null end as "rows_ok",
  case when (select kernel.field_visible('kernel.import', 'rows_failed')) then "rows_failed" else null end as "rows_failed",
  case when (select kernel.field_visible('kernel.import', 'file_attachment_id')) then "file_attachment_id" else null end as "file_attachment_id",
  case when (select kernel.field_visible('kernel.import', 'errors_attachment_id')) then "errors_attachment_id" else null end as "errors_attachment_id",
  case when (select kernel.field_visible('kernel.import', 'started_by')) then "started_by" else null end as "started_by",
  case when (select kernel.field_visible('kernel.import', 'finished_at')) then "finished_at" else null end as "finished_at",
  case when (select kernel.field_visible('kernel.import', 'error')) then "error" else null end as "error",
  "created_at",
  "updated_at"
from kernel.imports;
grant select on kernel.v_imports to authenticated;

