-- 0036 · The period figure in the masters' Tabla (gaps plan Task 7, OD-2 option A, design §22.20).
--
-- accounting.period_figure(kind, node_id, period_id) is the number the tree pane shows beside a node (masters/tree.ts): the
-- balance at the end of the period for an account (signed by its nature), the result of the period for a cost center and the
-- net movement for the other three dimensions, the node's descendants included. It reads only the published views, so a
-- restricted account is neither a node nor part of any figure (§5.13) and the answer is null when the node is not visible.
-- The five master views gain the column `period_figure`, which reads the grid param `period_id` (the transaction setting
-- `erp.param.period_id` the grid query sets, kernel/query/run.ts `applyGridParams`); without it the column is null.
-- The views are generated by maskedViewSql from the entities (views.test.ts fails when they drift).

create or replace function accounting.period_figure(p_kind text, p_node_id uuid, p_period_id uuid) returns numeric
language plpgsql stable security invoker
set search_path = ''
as $$
declare
  v_starts date;
  v_company uuid;
  v_nature text;
  v_total numeric;
  v_view text;
  v_column text;
  -- The sections of the income statement layout (the country packs' statementLayouts().incomeStatement).
  v_sections constant text[] := array['revenue', 'cost_of_sales', 'operating_expenses', 'other_income', 'other_expenses', 'income_tax'];
begin
  if p_period_id is null or p_node_id is null then return null; end if;
  select starts_on into v_starts from accounting.v_periods where id = p_period_id;
  if v_starts is null then return null; end if;

  if p_kind = 'account' then
    select company_id, nature into v_company, v_nature from accounting.v_accounts where id = p_node_id;
    if v_company is null then return null; end if;
    -- Every posted line up to the end of the period, debit minus credit, over the account and its visible descendants.
    with recursive below as (
      select id from accounting.v_accounts where id = p_node_id
      union
      select a.id from accounting.v_accounts a join below b on a.parent_id = b.id
    )
    select coalesce(sum(b.debit - b.credit), 0) into v_total
    from accounting.v_account_balances b join accounting.v_periods p on p.id = b.period_id
    where b.company_id = v_company and p.starts_on <= v_starts and b.account_id in (select id from below);
    return round(case when v_nature = 'credit' then -v_total else v_total end, 2);
  end if;

  v_view := case p_kind when 'cost_center' then 'v_cost_centers' when 'open_auxiliary' then 'v_open_auxiliaries' when 'item' then 'v_items' when 'business_unit' then 'v_business_units' end;
  v_column := case p_kind when 'cost_center' then 'cost_center_id' when 'open_auxiliary' then 'open_auxiliary_id' when 'item' then 'item_id' when 'business_unit' then 'business_unit_id' end;
  if v_view is null then raise exception 'period_figure: unknown kind %', p_kind; end if;
  execute format('select company_id from accounting.%I where id = $1', v_view) into v_company using p_node_id;
  if v_company is null then return null; end if;

  if p_kind = 'cost_center' then
    -- The result: what the income sections credit less what they debit (an expense subtracts), opening and year-close left out.
    execute format($q$
      with recursive below as (
        select id from accounting.%1$I where id = $1
        union
        select t.id from accounting.%1$I t join below b on t.parent_id = b.id
      )
      select coalesce(sum(b.credit - b.debit), 0)
      from accounting.v_account_balances b join accounting.v_accounts a on a.id = b.account_id
      where b.company_id = $2 and b.period_id = $3 and not b.is_opening and not b.is_closing
        and b.%2$I in (select id from below) and a.statement_section = any($4)$q$, v_view, v_column)
      into v_total using p_node_id, v_company, p_period_id, v_sections;
  else
    -- The net movement of the period: debit minus credit, opening and year-close left out.
    execute format($q$
      with recursive below as (
        select id from accounting.%1$I where id = $1
        union
        select t.id from accounting.%1$I t join below b on t.parent_id = b.id
      )
      select coalesce(sum(b.debit - b.credit), 0)
      from accounting.v_account_balances b
      where b.company_id = $2 and b.period_id = $3 and not b.is_opening and not b.is_closing and b.%2$I in (select id from below)$q$, v_view, v_column)
      into v_total using p_node_id, v_company, p_period_id;
  end if;
  return round(v_total, 2);
end;
$$;
revoke execute on function accounting.period_figure(text, uuid, uuid) from public, anon;
grant execute on function accounting.period_figure(text, uuid, uuid) to authenticated, service_role;

