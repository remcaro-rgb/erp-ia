-- ---------------------------------------------------------------------------------------------
-- One rounding rule for the company-currency amounts sales reads
-- ---------------------------------------------------------------------------------------------
create or replace view invoicing.v_order_invoiced with (security_invoker = true) as
select l.company_id, i.party_id, l.order_id, sum(round(l.total * i.exchange_rate, 2)) as invoiced_company
from invoicing.invoice_lines l join invoicing.invoices i on i.id = l.invoice_id
where l.order_id is not null and i.stage in ('issued', 'paid')
group by l.company_id, i.party_id, l.order_id;

create or replace view invoicing.v_open_invoices with (security_invoker = true) as
select i.company_id, i.party_id, i.id as invoice_id, i.number,
       greatest(i.total_company - round((i.paid_amount + i.credited_amount) * i.exchange_rate, 2), 0) as open_company
from invoicing.invoices i
where i.stage = 'issued' and i.total - i.paid_amount - i.credited_amount > 0;

-- ---------------------------------------------------------------------------------------------
-- The customer's credit: the customer filter reaches the invoicing views (same semantics and signature as 0093).
-- ---------------------------------------------------------------------------------------------
create or replace function sales.credit_exposure(p_party uuid, p_except uuid)
returns table (credit_limit numeric, exposure numeric)
language plpgsql volatile security definer
set search_path = ''
as $$
declare
  v_company uuid := kernel.current_company_id();
begin
  if v_company is null or not (array[v_company] <@ kernel.current_company_ids()) then
    raise exception 'no active company' using errcode = 'insufficient_privilege';
  end if;
  perform pg_advisory_xact_lock(hashtextextended('sales.credit:' || v_company::text || ':' || p_party::text, 0));
  return query
    select (select t.credit_limit from sales.customer_terms t where t.company_id = v_company and t.party_id = p_party),
           coalesce((select sum(greatest(o.total_company - coalesce(v.invoiced_company, 0), 0))
                     from sales.orders o
                     left join invoicing.v_order_invoiced v on v.company_id = v_company and v.party_id = p_party and v.order_id = o.id
                     where o.company_id = v_company and o.party_id = p_party and o.stage in ('confirmed', 'partially_delivered', 'delivered')
                       and o.status <> 'voided' and o.id is distinct from p_except), 0)
         + coalesce((select sum(x.open_company) from invoicing.v_open_invoices x where x.company_id = v_company and x.party_id = p_party), 0);
end;
$$;

-- ---------------------------------------------------------------------------------------------
-- INC and the other national taxes: their own account (backfill of the seeded charts)
-- ---------------------------------------------------------------------------------------------
insert into accounting.account_role_mappings (company_id, role, dimension, account_id)
select a.company_id, 'vat_out', 'tax:' || c.code, a.id
from accounting.accounts a
cross join (values ('INC2'), ('INC4'), ('INC8'), ('INC16'), ('22'), ('32'), ('33'), ('34'), ('35'), ('23')) as c(code)
where a.code = '249505'
  and exists (select 1 from accounting.account_role_mappings m where m.company_id = a.company_id)
  and not exists (
    select 1 from accounting.account_role_mappings m
    where m.company_id = a.company_id and m.role = 'vat_out' and m.dimension = 'tax:' || c.code);

