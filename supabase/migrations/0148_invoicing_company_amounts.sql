-- 0148_invoicing_company_amounts
-- Forward-only migration (rule 34), plan 2B.2 Task 34.4 (FX §4, §11; owner item 120, decided 2026-11-09; rule 8). Covered by
-- packages/modules/invoicing/src/__tests__/company-amounts.integration.test.ts (the backfill, the file run twice, the masked reads) and
-- entities.test.ts (the masked views are the generated ones). Re-runnable: every statement keys on what it has not done yet or recomputes
-- the same value.
--
-- Company-currency amounts are stored per line and per tax, not recomputed at posting (rule 8 literal): invoice_lines.subtotal_company,
-- invoice_taxes.amount_company, note_lines.subtotal_company, note_taxes.amount_company, numeric(18,4) not null. «Emitir» writes them with
-- companyAmounts() (per line half-up to the cent; the receivable is their sum, total_company). Existing rows are backfilled as the
-- document amount × the document's exchange_rate, rounded half-up to the cent (Postgres round(numeric, 2)): every existing row is COP at
-- rate 1, so each equals its document amount. Lines of issued documents are locked by their triggers (0092, 0096): the backfill runs with
-- the lock, the updated_at touch and the row audit off (a derived column, as 0042 and 0043 backfilled theirs) and turns them on again.
--
-- The masked views are re-created (generated by maskedViewSql from entities.ts): each company amount is visible only where its own field
-- and its document twin (base, amount) are, so a role that masks the document amount reads the pesos masked too (FX §10, rule 14).

alter table invoicing.invoice_lines add column if not exists subtotal_company numeric(18,4);
alter table invoicing.invoice_taxes add column if not exists amount_company numeric(18,4);
alter table invoicing.note_lines add column if not exists subtotal_company numeric(18,4);
alter table invoicing.note_taxes add column if not exists amount_company numeric(18,4);

alter table invoicing.invoice_lines disable trigger invoice_lines_locked;
alter table invoicing.invoice_lines disable trigger touch_row;
alter table invoicing.invoice_lines disable trigger audit_row_change;
alter table invoicing.invoice_taxes disable trigger invoice_taxes_locked;
alter table invoicing.invoice_taxes disable trigger touch_row;
alter table invoicing.invoice_taxes disable trigger audit_row_change;
alter table invoicing.note_lines disable trigger note_lines_locked;
alter table invoicing.note_lines disable trigger touch_row;
alter table invoicing.note_lines disable trigger audit_row_change;
alter table invoicing.note_taxes disable trigger note_taxes_locked;
alter table invoicing.note_taxes disable trigger touch_row;
alter table invoicing.note_taxes disable trigger audit_row_change;

update invoicing.invoice_lines l set subtotal_company = round(l.base * i.exchange_rate, 2)
  from invoicing.invoices i where i.id = l.invoice_id and l.subtotal_company is distinct from round(l.base * i.exchange_rate, 2);
update invoicing.invoice_taxes t set amount_company = round(t.amount * i.exchange_rate, 2)
  from invoicing.invoices i where i.id = t.invoice_id and t.amount_company is distinct from round(t.amount * i.exchange_rate, 2);
update invoicing.note_lines l set subtotal_company = round(l.base * n.exchange_rate, 2)
  from invoicing.notes n where n.id = l.note_id and l.subtotal_company is distinct from round(l.base * n.exchange_rate, 2);
update invoicing.note_taxes t set amount_company = round(t.amount * n.exchange_rate, 2)
  from invoicing.notes n where n.id = t.note_id and t.amount_company is distinct from round(t.amount * n.exchange_rate, 2);

