-- 0048_kernel_doc_templates
-- Forward-only migration (rule 34). Covered by packages/kernel/src/templates/__tests__/templates.integration.test.ts.
-- PDF templates (entity types spec 2026-11-02 §6, design §11, §22.23; Phase 2A.5 Task 11). The plan named this file 0046; 0044–0047 were
-- taken by Tasks 9 and 10 (controller ruling 2026-11-02).
--   - kernel.doc_templates: the company's templates per maestro / documento and scope (`record` | `list`), one default each; every save
--     is a new version (the version is kept by a trigger); written only by kernel.doc_template.save / set_default, company admins only.
--   - kernel.v_doc_templates: its masked read view (generated by maskedViewSql), so the template's files are kernel.attachments of the
--     entity `kernel.doc_template` (the background PDF, the logo).
--   - kernel.companies gains what a letterhead prints: address, city, phone and the logo (an image attachment of a template).
--   - kernel.export_jobs: a print is stored as a finished export job of its caller (same private bucket `exports`, same signed download).
--   - kernel.doc_template.print joins the baseline every role gets (kernel.seed_role_defaults), like kernel.export.run.
-- Kernel system table: no extra / extra_free (it holds no business data).

-- ---------------------------------------------------------------------------------------------
-- Templates.
-- ---------------------------------------------------------------------------------------------
create table kernel.doc_templates (
  id                 uuid primary key default kernel.uuid_v7(),
  seq                bigint not null,
  company_id         uuid not null references kernel.companies (id),
  entity             text not null check (entity ~ '^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)+$'),
  scope              text not null check (scope in ('record', 'list')),
  name               text not null check (btrim(name) <> '' and length(name) <= 120),
  -- A PDF attachment of this template (entity kernel.doc_template); its first page is the background of the first page, its second
  -- page (when it has one) of the continuation pages.
  background_file_id uuid references kernel.attachments (id),
  blocks             jsonb not null default '[]'::jsonb check (jsonb_typeof(blocks) = 'array'),
  is_default         boolean not null default false,
  version            int not null default 1 check (version >= 1),
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now(),
  created_by         uuid default kernel.current_user_id(),
  updated_by         uuid,
  unique (company_id, seq),
  unique (company_id, entity, scope, name)
);
-- One default per company, entity and scope (spec §6).
create unique index doc_templates_one_default on kernel.doc_templates (company_id, entity, scope) where is_default;

-- The version: 1 on insert; on update one more when the content changes or the save asks for it (every save is a new version), the
-- same otherwise (choosing the default is not a new version). The entity and scope of a template never change.
create or replace function kernel.doc_templates_version() returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    new.version := 1;
    return new;
  end if;
  if new.company_id is distinct from old.company_id or new.entity is distinct from old.entity or new.scope is distinct from old.scope then
    raise exception 'doc_templates_immutable: a template never changes company, entity or scope' using errcode = 'insufficient_privilege';
  end if;
  if (new.name, new.blocks, new.background_file_id) is distinct from (old.name, old.blocks, old.background_file_id) or new.version > old.version then
    new.version := old.version + 1;
  else
    new.version := old.version;
  end if;
  return new;
end;
$$;
create trigger doc_templates_version before insert or update on kernel.doc_templates
  for each row execute function kernel.doc_templates_version();

create trigger assign_seq before insert on kernel.doc_templates for each row execute function core.assign_seq('kernel.doc_template');
create trigger touch_row before update on kernel.doc_templates for each row execute function core.touch_row();

-- Members read their company's templates (printing reads them as the caller); company admins write them through the two processes.
-- Templates are never deleted (a print's audit names the template and its version).
grant select, insert, update on kernel.doc_templates to authenticated;
grant all on kernel.doc_templates to service_role;
select kernel.enable_company_rls('kernel', 'doc_templates');
select kernel.enable_row_audit('kernel', 'doc_templates');

create policy admin_writes on kernel.doc_templates as restrictive for insert to authenticated
  with check (
    (select kernel.is_company_admin())
    and coalesce(current_setting('erp.audit_process_id', true), '') = 'kernel.doc_template.save'
  );
create policy admin_updates on kernel.doc_templates as restrictive for update to authenticated
  using ((select kernel.is_company_admin()))
  with check (
    (select kernel.is_company_admin())
    and coalesce(current_setting('erp.audit_process_id', true), '') in ('kernel.doc_template.save', 'kernel.doc_template.set_default')
  );

-- The masked read view of kernel.doc_template (generated by maskedViewSql, rule 14).
create or replace view kernel.v_doc_templates with (security_invoker = true) as
select
  "id",
  "company_id",
  case when (select kernel.field_visible('kernel.doc_template', 'entity')) then "entity" else null end as "entity",
  case when (select kernel.field_visible('kernel.doc_template', 'scope')) then "scope" else null end as "scope",
  case when (select kernel.field_visible('kernel.doc_template', 'name')) then "name" else null end as "name",
  case when (select kernel.field_visible('kernel.doc_template', 'version')) then "version" else null end as "version",
  case when (select kernel.field_visible('kernel.doc_template', 'is_default')) then "is_default" else null end as "is_default",
  case when (select kernel.field_visible('kernel.doc_template', 'background_file_id')) then "background_file_id" else null end as "background_file_id",
  case when (select kernel.field_visible('kernel.doc_template', 'blocks')) then "blocks" else null end as "blocks",
  "created_at",
  "updated_at"
from kernel.doc_templates;
grant select on kernel.v_doc_templates to authenticated;

-- ---------------------------------------------------------------------------------------------
-- What a letterhead prints of the company (variables empresa.direccion, empresa.ciudad, empresa.telefono, empresa.logo). The phone is
-- stored as country code + number (rule 11). Set by kernel.admin.company.update.
-- ---------------------------------------------------------------------------------------------
alter table kernel.companies add column if not exists address_line text check (address_line is null or length(address_line) <= 200);
alter table kernel.companies add column if not exists city text check (city is null or length(city) <= 100);
alter table kernel.companies add column if not exists phone_cc text default '57' check (phone_cc is null or phone_cc ~ '^[0-9]{1,4}$');
alter table kernel.companies add column if not exists phone text check (phone is null or phone ~ '^[0-9]{4,15}$');
alter table kernel.companies add column if not exists logo_attachment_id uuid references kernel.attachments (id);
-- Written only by kernel.admin.company.update (its policy admin_update, 0021), like the names and the zone.
grant update (address_line, city, phone_cc, phone, logo_attachment_id) on kernel.companies to authenticated;

-- ---------------------------------------------------------------------------------------------
-- A print is a finished export job of its caller: kernel.doc_template.print inserts it done, with the stored file. Each process inserts
-- only its own kind of row: kernel.export.run a queued job without a file (the workflow finishes it), the print a finished PDF stored at
-- `<company>/<job>.pdf` of the active company.
-- ---------------------------------------------------------------------------------------------
alter policy via_process_insert on kernel.export_jobs
  with check (
    user_id = (select kernel.current_user_id())
    and (
      (coalesce(current_setting('erp.audit_process_id', true), '') = 'kernel.export.run'
        and status = 'queued' and storage_path is null)
      or (coalesce(current_setting('erp.audit_process_id', true), '') = 'kernel.doc_template.print'
        and status = 'done' and format = 'pdf' and storage_path = company_id::text || '/' || id::text || '.pdf')
    )
  );

-- ---------------------------------------------------------------------------------------------
-- Printing is part of every role's baseline (rule 13: it still needs the consult of the entity printed). Redefines 0022's
-- kernel.seed_role_defaults with kernel.doc_template.print next to kernel.export.run, and gives it to every existing role that may export.
-- ---------------------------------------------------------------------------------------------
create or replace function kernel.seed_role_defaults(p_company uuid, p_role uuid) returns void
language plpgsql security definer
set search_path = ''
as $$
declare
  v_admin boolean;
begin
  perform kernel.assert_admin_write(p_company);
  select r.is_system and r.name = 'admin' into v_admin from kernel.roles r where r.id = p_role and r.company_id = p_company;
  if v_admin is null then
    raise exception 'role % is not a role of company %', p_role, p_company using errcode = '22023';
  end if;

  if v_admin then
    insert into kernel.process_permissions (company_id, role_id, process_id)
    select p_company, p_role, rp.process_id from kernel.registered_processes rp
    on conflict (company_id, role_id, process_id) do nothing;
    return;
  end if;

  insert into kernel.process_permissions (company_id, role_id, process_id)
  select p_company, p_role, rp.process_id
  from kernel.registered_processes rp
  where rp.process_id in ('kernel.help.search', 'kernel.data.query', 'kernel.attachment.list', 'kernel.verify.status', 'kernel.export.run', 'kernel.doc_template.print')
     or rp.process_id like 'kernel.saved\_view.%'
     or rp.process_id like 'kernel.user\_prefs.%'
     or rp.process_id like 'kernel.home.%'
     or rp.process_id like 'kernel.recommendation.%'
     or (rp.kind = 'consult' and rp.module_id <> 'kernel' and kernel.entitled(p_company, 'module:' || rp.module_id))
  on conflict (company_id, role_id, process_id) do nothing;

  insert into kernel.field_permissions (company_id, role_id, entity, field, mode)
  select p_company, p_role, ef.entity, ef.field, 'masked'
  from kernel.entity_fields ef
  where ef.sensitivity = 'confidential'
  on conflict (company_id, role_id, entity, field) do nothing;
end;
$$;
revoke execute on function kernel.seed_role_defaults(uuid, uuid) from public, anon;
grant execute on function kernel.seed_role_defaults(uuid, uuid) to authenticated, service_role;

insert into kernel.process_permissions (company_id, role_id, process_id)
select pp.company_id, pp.role_id, 'kernel.doc_template.print'
from kernel.process_permissions pp
join kernel.roles r on r.id = pp.role_id
where pp.process_id = 'kernel.export.run' and pp.allowed and not (r.is_system and r.name = 'admin')
on conflict (company_id, role_id, process_id) do nothing;
