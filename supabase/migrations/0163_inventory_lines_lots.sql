-- 0163_inventory_lines_lots
-- Forward-only migration (rule 34). Covered by packages/modules/inventory/src/__tests__/movement-lots.integration.test.ts and entities.test.ts
-- (the masked views match the entity definitions). Plan 2B.2 Task 28.2 (Part G design PG §3.2; RG-2, RG-3):
--   * inventory.transfer_lines and inventory.count_lines gain lot_id and serial_id, with FKs on (id, product_id) to the maestros of 0162:
--     a traslado line carries its lot (or one serial) through transit; a conteo line counts one bucket (product, ubicación, lot, serial).
--     Untracked lines keep both null (RG-2).
--   * The conteo's bucket key now includes lot and serial, so a product counted per lot or serial has one line per bucket.
--   * inventory.count_lines_guard (0069) now lets an open conteo take a line for a lot or serial the counter found (inventory.count.record,
--     `found`), and keeps the bucket of every line (lot, serial too) frozen once the conteo is saved.
--   * The masked views v_transfer_lines and v_count_lines are re-created with the two columns appended.

alter table inventory.transfer_lines
  add column lot_id uuid,
  add column serial_id uuid,
  add constraint transfer_lines_lot_fkey foreign key (lot_id, product_id) references inventory.lots (id, product_id),
  add constraint transfer_lines_serial_fkey foreign key (serial_id, product_id) references inventory.serials (id, product_id),
  -- A serial line moves exactly one unit.
  add constraint transfer_lines_serial_qty_check check (serial_id is null or qty = 1);

alter table inventory.count_lines
  add column lot_id uuid,
  add column serial_id uuid,
  add constraint count_lines_lot_fkey foreign key (lot_id, product_id) references inventory.lots (id, product_id),
  add constraint count_lines_serial_fkey foreign key (serial_id, product_id) references inventory.serials (id, product_id),
  -- A serial is counted found (1) or missing (0).
  add constraint count_lines_serial_qty_check check (serial_id is null or counted_qty is null or counted_qty in (0, 1));

drop index inventory.count_lines_bucket_key;
create unique index count_lines_bucket_key on inventory.count_lines (count_id, product_id, location_id, lot_id, serial_id) nulls not distinct;
create index transfer_lines_lot_idx on inventory.transfer_lines (lot_id) where lot_id is not null;
create index transfer_lines_serial_idx on inventory.transfer_lines (serial_id) where serial_id is not null;
create index count_lines_lot_idx on inventory.count_lines (lot_id) where lot_id is not null;
create index count_lines_serial_idx on inventory.count_lines (serial_id) where serial_id is not null;

create or replace function inventory.count_lines_guard() returns trigger
language plpgsql
as $$
declare
  v_count uuid := case when tg_op = 'DELETE' then old.count_id else new.count_id end;
  v_status text;
  v_stage text;
begin
  select status, stage into v_status, v_stage from inventory.counts where id = v_count;
  if v_status = 'draft' then
    return case when tg_op = 'DELETE' then old else new end;
  end if;
  if tg_op = 'UPDATE' and v_stage = 'open' and v_status <> 'voided'
     and (new.count_id, new.line_no, new.product_id, new.location_id, new.lot_id, new.serial_id)
         is not distinct from (old.count_id, old.line_no, old.product_id, old.location_id, old.lot_id, old.serial_id) then
    return new;
  end if;
  -- A lot or serial found while counting (Task 28.2) becomes a line of the open conteo.
  if tg_op = 'INSERT' and v_stage = 'open' and v_status <> 'voided' and (new.lot_id is not null or new.serial_id is not null) then
    return new;
  end if;
  raise exception 'erp:invalid_input:Las líneas de un conteo aplicado o anulado no cambian';
end;
$$;

