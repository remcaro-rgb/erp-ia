-- 0016_kernel_export_jobs
-- Forward-only migration (rule 34). Covered by apps/web/src/app/api/export/__tests__/export-route.integration.test.ts
-- (an export of 10,001 rows runs as a job and ends `done`; a job is visible only to who started it and to company admins).
-- Exports of a grid to CSV, Excel or PDF (design §9, rule 20): under 10,000 rows the route streams the file at once;
-- from there on `kernel.export.run` creates a job here and the export workflow renders the file into the private
-- storage bucket `exports`, keeping the job's status and counts (service role).
-- Beyond company RLS, a member sees only the jobs they started; company admins see every job of the company.

create table kernel.export_jobs (
  id           uuid primary key default kernel.uuid_v7(),
  company_id   uuid not null references kernel.companies (id),
  user_id      uuid not null references kernel.users (id),
  entity       text not null check (entity ~ '^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)+$'),
  format       text not null check (format in ('csv', 'xlsx', 'pdf')),
  -- What the job was asked for: the grid state, the headers and the value labels the caller's screen showed.
  state        jsonb not null default '{}'::jsonb,
  status       text not null default 'queued' check (status in ('queued', 'running', 'done', 'failed')),
  -- <company>/<job>.<ext> in the bucket `exports`, set when the file is stored.
  storage_path text,
  file_name    text,
  row_count    int check (row_count >= 0),
  error        text,
  finished_at  timestamptz,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  created_by   uuid default kernel.current_user_id(),
  updated_by   uuid
);
create index export_jobs_company_created_idx on kernel.export_jobs (company_id, created_at desc);
create index export_jobs_user_id_idx on kernel.export_jobs (user_id);

create trigger export_jobs_touch_updated before update on kernel.export_jobs
  for each row execute function kernel.touch_updated();

-- Members insert through kernel.export.run; status, counts and the file change only with the service role (the workflow).
grant select, insert on kernel.export_jobs to authenticated;
grant all on kernel.export_jobs to service_role;
select kernel.enable_company_rls('kernel', 'export_jobs');
select kernel.enable_row_audit('kernel', 'export_jobs');

-- Writes only through the process pipeline (rule 1): the caller starts an export as themselves.
create policy via_process_insert on kernel.export_jobs as restrictive for insert to authenticated
  with check (
    coalesce(current_setting('erp.audit_process_id', true), '') = 'kernel.export.run'
    and user_id = (select kernel.current_user_id())
  );

-- A job is visible to who started it and to company admins.
create policy own_or_admin on kernel.export_jobs as restrictive for all to authenticated
  using (user_id = (select kernel.current_user_id()) or (select kernel.is_company_admin()))
  with check (user_id = (select kernel.current_user_id()) or (select kernel.is_company_admin()));

-- The masked read view of kernel.export_job (generated by maskedViewSql up to its `from`, rule 14) with the same
-- predicate as the policy, so the view never depends on the base table's policies alone. `state` is not published.
create or replace view kernel.v_export_jobs with (security_invoker = true) as
select
  "id",
  "company_id",
  case when (select kernel.field_visible('kernel.export_job', 'entity')) then "entity" else null end as "entity",
  case when (select kernel.field_visible('kernel.export_job', 'format')) then "format" else null end as "format",
  case when (select kernel.field_visible('kernel.export_job', 'status')) then "status" else null end as "status",
  case when (select kernel.field_visible('kernel.export_job', 'row_count')) then "row_count" else null end as "row_count",
  case when (select kernel.field_visible('kernel.export_job', 'file_name')) then "file_name" else null end as "file_name",
  case when (select kernel.field_visible('kernel.export_job', 'storage_path')) then "storage_path" else null end as "storage_path",
  case when (select kernel.field_visible('kernel.export_job', 'error')) then "error" else null end as "error",
  case when (select kernel.field_visible('kernel.export_job', 'user_id')) then "user_id" else null end as "user_id",
  case when (select kernel.field_visible('kernel.export_job', 'finished_at')) then "finished_at" else null end as "finished_at",
  "created_at",
  "updated_at"
from kernel.export_jobs
where user_id = (select kernel.current_user_id()) or (select kernel.is_company_admin());
grant select on kernel.v_export_jobs to authenticated;

-- ---------------------------------------------------------------------------------------------
-- Storage: the private bucket `exports` (50 MiB per object, the storage service's own limit). Like `attachments`
-- (0007) no policy lets a user touch it: only the service role writes, from the export workflow, and downloads are
-- signed URLs minted server-side (10 minutes) after the route checked the job belongs to the caller.
-- ---------------------------------------------------------------------------------------------
insert into storage.buckets (id, name, public, file_size_limit)
values ('exports', 'exports', false, 52428800)
on conflict (id) do nothing;

create policy exports_service_role_only on storage.objects for all to service_role
  using (bucket_id = 'exports') with check (bucket_id = 'exports');
