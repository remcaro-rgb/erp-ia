-- The rule «Aplicación de anticipo» with both amounts and the realized difference (R34-5: only the copies nobody edited).
-- ---------------------------------------------------------------------------------------------
update accounting.posting_rules
   set template = $tpl${"date":"$.date","description":"Aplicación de anticipo {{number}} · {{customer.legalName}}","party":"$.customer.partyId","currency":"$.currency","exchangeRate":"$.exchangeRate","source":{"entity":"payments.advance_application","id":"$.applicationId"},"lines":[{"role":"customer_advances","side":"debit","amount":"$.drawnDoc","amountCompany":"$.drawn"},{"role":"fx_loss","side":"debit","forEach":"$.allocations[*]","amount":"0","amountCompany":"$.fx.loss","dimension":"fx_kind:realized"},{"role":"receivable","side":"credit","amount":"$.totalDoc","amountCompany":"$.total"},{"role":"fx_gain","side":"credit","forEach":"$.allocations[*]","amount":"0","amountCompany":"$.fx.gain","dimension":"fx_kind:realized"}],"reverseOf":null}$tpl$::jsonb
 where event = 'payments.advance.applied' and name = 'Aplicación de anticipo'
   and is_default and not is_modified and not (template ? 'currency');

do $$
declare
  kept text;
begin
  select string_agg(distinct company_id::text, ', ') into kept
    from accounting.posting_rules
   where event = 'payments.advance.applied' and name = 'Aplicación de anticipo' and is_modified and not (template ? 'currency');
  if kept is not null then
    raise notice 'advance application rules without a currency path left as the admin edited them, for companies: %', kept;
  end if;
end $$;

