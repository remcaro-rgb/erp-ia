create or replace function invoicing.note_delete_draft_only() returns trigger
language plpgsql
as $$
begin
  if old.status <> 'draft' or old.stage <> 'draft' or old.number is not null then
    raise exception 'erp:invalid_input:Solo se elimina una nota en Borrador (sin número): una nota emitida no se anula, se corrige con otra nota';
  end if;
  return old;
end;
$$;
