-- The invoice: what its debit notes added; the annulment note it names
-- =============================================================================================
alter table invoicing.invoices add column debited_amount numeric(18,4) not null default 0 check (debited_amount >= 0);

create or replace function invoicing.invoice_issued_frozen() returns trigger
language plpgsql
as $$
declare
  v_moving constant text[] := array['dian_status', 'paid_amount', 'credited_amount', 'debited_amount', 'stage', 'annulment_note_id', 'status', 'void_reason', 'updated_at', 'updated_by'];
begin
  if old.stage = 'draft' then
    if new.stage not in ('draft', 'issued') then
      raise exception 'erp:invalid_input:Una factura en Borrador solo se emite';
    end if;
    return new;
  end if;
  if (to_jsonb(new) - v_moving) is distinct from (to_jsonb(old) - v_moving) then
    raise exception 'erp:invalid_input:Una factura emitida no cambia: se corrige con una nota crédito o débito';
  end if;
  if new.stage = 'draft' or (old.stage = 'voided' and new.stage <> 'voided') then
    raise exception 'erp:invalid_input:Una factura emitida no vuelve a Borrador y una anulada no cambia';
  end if;
  if old.annulment_note_id is not null and new.annulment_note_id is distinct from old.annulment_note_id then
    raise exception 'erp:invalid_input:La nota de anulación de una factura no cambia';
  end if;
  return new;
end;
$$;

-- =============================================================================================
-- Notas crédito y débito
-- =============================================================================================
-- Money (rule 8): amounts positive in the note's currency (the invoice's, with its exchange-rate snapshot), the total also in the company
-- currency; the posting signs them (a credit note's are negative). `concept` is the code of the pack's correction table of the kind;
-- `annulment` marks the full credit note of an Anular (concept 2: Anulación de factura electrónica). `resolution` is the numbering range the
-- number was drawn from (never its key).
create table invoicing.notes (
  id             uuid primary key default kernel.uuid_v7(),
  seq            bigint not null,
  company_id     uuid not null references kernel.companies (id),
  kind           text not null check (kind in ('credit', 'debit')),
  number         text,
  prefix         text,
  consecutive    bigint check (consecutive is null or consecutive > 0),
  cude           text check (cude is null or cude ~ '^[0-9a-f]{96}$'),
  invoice_id     uuid not null references invoicing.invoices (id),
  party_id       uuid not null,
  concept        text not null check (concept ~ '^[0-9]{1,2}$'),
  annulment      boolean not null default false,
  reason         text not null check (char_length(reason) between 1 and 500),
  issue_date     date not null,
  issue_time     text check (issue_time is null or issue_time ~ '^\d{2}:\d{2}:\d{2}[+-]\d{2}:\d{2}$'),
  due_date       date,
  stage          text not null default 'draft' check (stage in ('draft', 'issued')),
  dian_status    text not null default 'draft' check (dian_status in ('draft', 'submitted', 'accepted', 'rejected')),
  currency       text not null default 'COP' check (currency ~ '^[A-Z]{3}$'),
  exchange_rate  numeric(18,6) not null default 1 check (exchange_rate > 0),
  subtotal       numeric(18,4) not null default 0 check (subtotal >= 0),
  tax_total      numeric(18,4) not null default 0 check (tax_total >= 0),
  total          numeric(18,4) not null default 0 check (total >= 0),
  total_company  numeric(18,4) not null default 0 check (total_company >= 0),
  resolution     jsonb,
  cost_center_id uuid,
  issued_at      timestamptz,
  notes          text check (notes is null or char_length(notes) <= 2000),
  extra          jsonb not null default '{}'::jsonb,
  extra_free     jsonb not null default '[]'::jsonb,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now(),
  created_by     uuid default kernel.current_user_id(),
  updated_by     uuid,
  unique (company_id, seq),
  unique (company_id, kind, number),
  unique (company_id, cude),
  check (due_date is null or due_date >= issue_date),
  check (stage = 'draft' or (number is not null and issued_at is not null)),
  -- The annulment is a full credit note of concept 2 (rule CAD02a: CustomizationID 20, set by the pack's builder).
  check (not annulment or (kind = 'credit' and concept = '2')),
  -- A note is sent to the DIAN once issued; its CUDE comes with its first sending.
  check (stage = 'issued' or (dian_status = 'draft' and cude is null))
);
