-- An issued note keeps what was issued; only its DIAN status, its CUDE (set once, at its first sending) and the lifecycle's columns move. A
-- note is never voided (a DIAN document: it is corrected by another note).
create or replace function invoicing.note_issued_frozen() returns trigger
language plpgsql
as $$
declare
  v_moving constant text[] := array['dian_status', 'cude', 'status', 'updated_at', 'updated_by'];
begin
  if old.stage = 'draft' then
    return new;
  end if;
  if (to_jsonb(new) - v_moving) is distinct from (to_jsonb(old) - v_moving) then
    raise exception 'erp:invalid_input:Una nota emitida no cambia: se corrige con otra nota';
  end if;
  if old.cude is not null and new.cude is distinct from old.cude then
    raise exception 'erp:invalid_input:El CUDE de una nota no cambia';
  end if;
  if new.status = 'voided' then
    raise exception 'erp:invalid_input:Una nota electrónica no se anula: se corrige con otra nota';
  end if;
  return new;
end;
$$;
create trigger note_issued_frozen before update on invoicing.notes for each row execute function invoicing.note_issued_frozen();

create or replace function invoicing.note_parts_locked() returns trigger
language plpgsql
as $$
declare
  v_note uuid := case when tg_op = 'DELETE' then old.note_id else new.note_id end;
  v_stage text;
begin
  select stage into v_stage from invoicing.notes where id = v_note;
  if v_stage is null or v_stage = 'draft' then
    return case when tg_op = 'DELETE' then old else new end;
  end if;
  raise exception 'erp:invalid_input:Las líneas de una nota emitida no cambian';
end;
$$;
create trigger note_lines_locked before insert or update or delete on invoicing.note_lines
  for each row execute function invoicing.note_parts_locked();
create trigger note_taxes_locked before insert or update or delete on invoicing.note_taxes
  for each row execute function invoicing.note_parts_locked();

-- The DIAN status of a note only moves forward, as an invoice's (0095).
create or replace function invoicing.note_dian_status_forward() returns trigger
language plpgsql
as $$
begin
  if new.dian_status is not distinct from old.dian_status then
    return new;
  end if;
  if new.stage = 'draft' then
    raise exception 'erp:invalid_input:Una nota en Borrador no se envía a la DIAN';
  end if;
  if not ((old.dian_status = 'draft' and new.dian_status = 'submitted')
       or (old.dian_status = 'submitted' and new.dian_status in ('accepted', 'rejected'))
       or (old.dian_status = 'rejected' and new.dian_status = 'submitted')) then
    raise exception 'erp:invalid_input:El estado DIAN de la nota no pasa de % a %', old.dian_status, new.dian_status;
  end if;
  return new;
end;
$$;
create trigger note_dian_status_forward before update of dian_status on invoicing.notes
  for each row execute function invoicing.note_dian_status_forward();

