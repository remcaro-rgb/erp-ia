-- =============================================================================================
-- Published for sales (rule 3): the open invoices count what their debit notes added
-- =============================================================================================
create or replace view invoicing.v_open_invoices with (security_invoker = true) as
select i.company_id, i.party_id, i.id as invoice_id, i.number,
       greatest(i.total_company + round(i.debited_amount * i.exchange_rate, 2) - round((i.paid_amount + i.credited_amount) * i.exchange_rate, 2), 0) as open_company
from invoicing.invoices i
where i.stage = 'issued' and i.total + i.debited_amount - i.paid_amount - i.credited_amount > 0;

