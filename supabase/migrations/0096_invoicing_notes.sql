-- 0096_invoicing_notes
-- Forward-only migration (rule 34). Covered by packages/modules/invoicing/src/__tests__/note.integration.test.ts (credit and debit notes,
-- the annulment of an invoice by its credit note, the DIAN submission of a note on the mock transport, the bulk «Reintentar envío») and
-- entities.test.ts (the masked views match the entity definitions).
-- Credit and debit notes and the annulment of an issued invoice (plan 2B Task 18, which named it 0069; 0096 was the next free number; design
-- §8, §8.1, OD-7 of §22.25):
--   * invoicing.notes (documento, contabiliza) with invoicing.note_lines and invoicing.note_taxes: a credit or debit note of an issued invoice,
--     its correction concept (DIAN tables 13.2.4 / 13.2.5, the pack's), the invoice line each of its lines corrects, its own numbering
--     (core.next_document_number, credit_note / debit_note) and its CUDE (computed by the e-invoice workflow, which holds the software PIN).
--     A note names an invoice (a foreign key to invoicing.invoices): never another note (Oficio DIAN 129 of 2023). One annulment note per
--     invoice (a partial unique index): two Anular of the same invoice give one note;
--   * invoicing.invoices.debited_amount (what its debit notes added) and the frozen invoice lets it move; the annulment note it names is a
--     foreign key; v_open_invoices counts the debits. invoicing.v_invoices is recreated with it (generated by maskedViewSql);
--   * invoicing.einvoice_submissions gains note_id: a note is sent like an invoice, one submission per note (invoice_id is then the invoice
--     it corrects, whose read right the row inherits); one submission per invoice of its own (note_id null). v_einvoice_submissions is
--     recreated with it.
-- Company RLS, row audit, seq, extra / extra_free, writes only through the invoicing processes (restrictive policies on erp.audit_process_id),
-- the note's read right on its lines and taxes (kernel.typed_lines).

