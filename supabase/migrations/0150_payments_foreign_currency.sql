-- ---------------------------------------------------------------------------------------------
-- What settled each invoice, in its currency and in pesos: the posted receipts' allocations and the posted applications' lines, for
-- «Registrar pago» (the allocation that closes an invoice takes the pesos still open at the invoice's rate, FX §5). A function of its own:
-- payments.allocated_amounts, published for invoicing, keeps its signature (0137). Payments processes only, same company guard and grants.
-- ---------------------------------------------------------------------------------------------
create or replace function payments.allocated_company_amounts(p_invoices uuid[])
returns table (invoice_id uuid, allocated numeric, allocated_company numeric)
language plpgsql stable security definer
set search_path = ''
as $$
declare
  v_company uuid := kernel.current_company_id();
  v_process text := coalesce(current_setting('erp.audit_process_id', true), '');
begin
  if v_process not like 'payments.%' then
    raise exception 'payments.allocated_company_amounts is called only inside a payments process' using errcode = 'insufficient_privilege';
  end if;
  if v_company is null or not (array[v_company] <@ kernel.current_company_ids()) then
    raise exception 'no active company' using errcode = 'insufficient_privilege';
  end if;
  return query
    select s.invoice_id, sum(s.amount)::numeric, sum(s.amount_company)::numeric
    from (
      select a.invoice_id, a.amount, a.amount_company
      from payments.receipt_allocations a join payments.receipts r on r.id = a.receipt_id
      where a.company_id = v_company and a.invoice_id = any (p_invoices) and r.status = 'posted'
      union all
      select l.invoice_id, l.amount, l.amount_company
      from payments.advance_application_lines l join payments.advance_applications p on p.id = l.application_id
      where l.company_id = v_company and l.invoice_id = any (p_invoices) and p.status = 'posted'
    ) s
    group by s.invoice_id;
end;
$$;
revoke execute on function payments.allocated_company_amounts(uuid[]) from public, anon;
grant execute on function payments.allocated_company_amounts(uuid[]) to authenticated, service_role;
comment on function payments.allocated_company_amounts(uuid[]) is
  'What the posted receipts and the posted advance applications settled of each invoice, in its currency and in the company''s, every one of the active company. Payments processes only.';

-- ---------------------------------------------------------------------------------------------
-- Published by payments for accounting (rule 3): every allocation of the company with its amount in the invoice's currency, in the receipt's
-- and in the company's (plan Task 34.7 splits a receipt's receivable line by amount_company). As 0114 and 0137 left it, executable only by
-- its owner (accounting.open_items_allocated, a definer).
-- ---------------------------------------------------------------------------------------------
drop function if exists payments.ledger_allocations(uuid);
create function payments.ledger_allocations(p_company uuid)
returns table (receipt_id uuid, invoice_id uuid, amount numeric, amount_receipt numeric, amount_company numeric)
language sql stable security definer
set search_path = ''
as $$
  select a.receipt_id, a.invoice_id, a.amount, a.amount_receipt, a.amount_company
  from payments.receipt_allocations a
  where a.company_id = p_company and array[p_company] <@ kernel.current_company_ids()
  union all
  select l.application_id, l.invoice_id, sum(l.amount), sum(l.amount), sum(l.amount_company)
  from payments.advance_application_lines l
  where l.company_id = p_company and array[p_company] <@ kernel.current_company_ids()
  group by l.application_id, l.invoice_id;
$$;
revoke execute on function payments.ledger_allocations(uuid) from public, anon, authenticated, service_role;
comment on function payments.ledger_allocations(uuid) is
  'Published for accounting (rule 3): receipt (or advance application) → invoice → amount in the invoice''s currency, in the receipt''s and in the company''s, of every allocation of a company the caller belongs to. Definer, executable only by its owner (accounting.open_items_allocated).';

