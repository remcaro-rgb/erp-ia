-- 0150_payments_foreign_currency
-- Forward-only migration (rule 34), plan 2B.2 Task 34.5 (FX §6, §11; owner items 120 and 125, decided 2026-11-09; rule 8; ruling R34-6).
-- Covered by packages/modules/payments/src/__tests__/receipt-fx.integration.test.ts («0150 on existing rows»: the backfill, the file run
-- twice; the foreign receipts) and entities.test.ts (the masked views are the generated ones). Re-runnable: every statement keys on what it
-- has not done yet or recomputes the same value.
--
--   * payments.methods.currency char(3) not null: the money the method receives (ISO 4217). A receipt goes only through a method of its own
--     currency (method_currency_mismatch), so a USD receipt lands in the bank account its method's kind maps to (FX §6, no new role). When an
--     insert gives none, the company's currency (a trigger: a column default cannot read the company); existing methods take it.
--   * payments.receipt_allocations.amount_receipt and amount_company numeric(18,4) not null: what an allocation settles in the receipt's
--     currency (pesos received against a USD invoice, item 125) and in the company's currency at the invoice's rate (what it takes off the
--     receivable; the difference to the receipt's pesos is the realized exchange difference, FX §5). `amount` stays in the invoice's currency.
--   * payments.advance_application_lines.amount_company numeric(18,4) not null: the line's pesos (no behaviour yet: advances stay in COP until
--     plan Task 34.6, which reads it).
--   Every existing row is COP at rate 1, so each new amount is its `amount`. Allocations and application lines of a posted document are
--   frozen by their triggers (0109, 0137): the backfill runs with the freeze, the updated_at touch and the row audit off (derived columns,
--   as 0148 did) and turns them on again.
--   * The cash and the withholdings of an allocation are in the receipt's currency: the row check becomes amount_receipt = cash_amount +
--     withholding_total (receipt_allocations_receipt_split, in place of receipt_allocations_check of 0109).
--   * payments.allocated_company_amounts (new, payments processes only) answers what settled each invoice in its currency and in pesos;
--     payments.allocated_amounts, published for invoicing, keeps its signature. payments.ledger_allocations answers the receipt's and the
--     company's amounts too (dropped and created again: a function's result columns cannot change in place); same grants as 0114.
--   * The masked views of the three entities are re-created (generated by maskedViewSql from entities.ts; the columns sit in the middle).

