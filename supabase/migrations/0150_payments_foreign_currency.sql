create or replace function payments.method_currency_default() returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.currency is null then
    select c.currency_code into new.currency from kernel.companies c where c.id = new.company_id;
  end if;
  return new;
end;
$$;
drop trigger if exists method_currency_default on payments.methods;
create trigger method_currency_default before insert on payments.methods for each row execute function payments.method_currency_default();

