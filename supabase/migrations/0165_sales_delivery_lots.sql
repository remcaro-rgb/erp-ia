-- 0165_sales_delivery_lots
-- Forward-only migration (rule 34). Covered by packages/modules/sales/src/__tests__/delivery-lots.integration.test.ts and entities.test.ts
-- (the masked views match the entity definitions). Plan 2B.2 Task 28.3 (Part G design PG §3.1, §3.3; RG-4):
--   * sales.delivery_lines and sales.return_lines gain lot_id (inventory's lot: no foreign key across schemas, rule 3) and serial_ids
--     uuid[]: what the user asks for (a lot, or one serial per unit; else inventory issues a lot product by FEFO at ship).
--   * sales.delivery_line_lots (sistema sales.delivery_line_lot): what inventory actually issued of each lot and serial for an entrega
--     line, written once per inventory.sale_issue.allocated event by sales.delivery.record_lots (event_id kept), read-only.
--   * Masked views (rule 14): v_delivery_lines gains lot_id, serial_ids and the read-only «Lote / Vence / Serie» (lots); v_return_lines
--     gains lot_id and serial_ids; v_delivery_line_lots is new and published (invoicing copies it onto the invoice line, Task 28.4).

alter table sales.delivery_lines
  add column lot_id uuid,
  add column serial_ids uuid[],
  add constraint delivery_lines_lot_or_serials check (lot_id is null or serial_ids is null),
  add constraint delivery_lines_serial_count check (serial_ids is null or cardinality(serial_ids) = qty);
alter table sales.return_lines
  add column lot_id uuid,
  add column serial_ids uuid[],
  add constraint return_lines_lot_or_serials check (lot_id is null or serial_ids is null),
  add constraint return_lines_serial_count check (serial_ids is null or cardinality(serial_ids) = qty);

create table sales.delivery_line_lots (
  id               uuid primary key default kernel.uuid_v7(),
  seq              bigint not null,
  company_id       uuid not null references kernel.companies (id),
  delivery_line_id uuid not null references sales.delivery_lines (id),
  lot_id           uuid,
  lot_code         text check (lot_code is null or char_length(lot_code) <= 60),
  expires_on       date,
  serial_id        uuid,
  serial_no        text check (serial_no is null or char_length(serial_no) <= 80),
  qty              numeric(18,4) not null check (qty > 0),
  event_id         uuid not null,
  extra            jsonb not null default '{}'::jsonb,
  extra_free       jsonb not null default '[]'::jsonb,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  created_by       uuid default kernel.current_user_id(),
  updated_by       uuid,
  unique (company_id, seq),
  check (lot_id is not null or serial_id is not null)
);
-- One entry per entrega line and lot or serial: a redelivered event (or a second event for the same issue) cannot write it twice.
create unique index delivery_line_lots_bucket_key on sales.delivery_line_lots (delivery_line_id, lot_id, serial_id) nulls not distinct;
create index delivery_line_lots_lot_idx on sales.delivery_line_lots (company_id, lot_id) where lot_id is not null;
create index delivery_line_lots_serial_idx on sales.delivery_line_lots (company_id, serial_id) where serial_id is not null;

select kernel.enable_company_rls('sales', 'delivery_line_lots');
select kernel.enable_row_audit('sales', 'delivery_line_lots');
create trigger assign_seq before insert on sales.delivery_line_lots for each row execute function core.assign_seq('sales.delivery_line_lot');
create trigger touch_row before update on sales.delivery_line_lots for each row execute function core.touch_row();
grant select, insert, update, delete on sales.delivery_line_lots to authenticated;
grant all on sales.delivery_line_lots to service_role;
-- Writes only through sales.delivery.record_lots (an entrega process).
create policy via_process_insert on sales.delivery_line_lots as restrictive for insert to authenticated
  with check (coalesce(current_setting('erp.audit_process_id', true), '') like 'sales.delivery.%');
create policy via_process_update on sales.delivery_line_lots as restrictive for update to authenticated
  using (coalesce(current_setting('erp.audit_process_id', true), '') like 'sales.delivery.%')
  with check (coalesce(current_setting('erp.audit_process_id', true), '') like 'sales.delivery.%');
create policy via_process_delete on sales.delivery_line_lots as restrictive for delete to authenticated
  using (coalesce(current_setting('erp.audit_process_id', true), '') like 'sales.delivery.%');

select kernel.register_reference('inventory.lot', 'sales', 'delivery_lines',     'lot_id');
select kernel.register_reference('inventory.lot', 'sales', 'return_lines',       'lot_id');
select kernel.register_reference('inventory.lot', 'sales', 'delivery_line_lots', 'lot_id');

